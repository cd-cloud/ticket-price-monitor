def candidate_by_code(code: str) -> TailDestination | None:
    normalized = code.strip().upper()
    return next((item for item in TAIL_DESTINATIONS if item.code == normalized), None)


def default_tail_codes_for_airlines(
    preferred_airlines: list[str] | None,
    candidate_profile: str | None = None,
) -> tuple[str, ...]:
    profile = str(candidate_profile or "").strip().upper()
    if profile in {"ALL_DOMESTIC", "DOMESTIC_ALL", "FULL_DOMESTIC"}:
        return ALL_DOMESTIC_TAIL_CODES
    requested = {str(item or "").strip().upper() for item in preferred_airlines or [] if str(item or "").strip()}
    if not requested:
        return DEFAULT_TAIL_TEST_CODES
    if {"CA", "ZH", "TV", "SC", "KY", "NX"}.issubset(requested) or "AIR_CHINA_GROUP" in requested:
        return AIRLINE_TAIL_DEFAULTS["AIR_CHINA_GROUP"]
    for code in ("CA", "CZ", "MU"):
        if code in requested:
            return AIRLINE_TAIL_DEFAULTS[code]
    return DEFAULT_TAIL_TEST_CODES


def prioritize_tail_codes(codes: list[str], preferred_airlines: list[str] | None) -> list[str]:
    requested = {str(item or "").strip().upper() for item in preferred_airlines or [] if str(item or "").strip()}
    profile_codes: tuple[str, ...] = ()
    if {"CA", "ZH", "TV", "SC", "KY", "NX"}.issubset(requested) or "AIR_CHINA_GROUP" in requested:
        profile_codes = AIRLINE_TAIL_DEFAULTS["AIR_CHINA_GROUP"]
    else:
        for code in ("CA", "CZ", "MU"):
            if code in requested:
                profile_codes = AIRLINE_TAIL_DEFAULTS[code]
                break
    priority = {code: index for index, code in enumerate(profile_codes)}
    return sorted(
        dict.fromkeys(code.strip().upper() for code in codes if code).keys(),
        key=lambda code: (priority.get(code, 999), code),
    )
